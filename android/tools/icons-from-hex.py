#!/usr/bin/env python3
"""Turns the line icons in Hex's src/rune_ui/icons.rs into Android vector
drawables (res/drawable/hex_icon_<name>.xml), so the app's rows use Hex's
own icons: a 24 point grid, 1.75 stroke, round caps and joins.

Run from android/: tools/icons-from-hex.py. Only the icons in USED are
written; add a name here (Hex's constant, lower case) to use another.
"""
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent.parent
source = (here.parent / "src/rune_ui/icons.rs").read_text()
out = here / "app/src/main/res/drawable"

USED = {
    "bell", "book", "circle_x", "folder", "hand", "mic", "paste", "refresh",
    "sparkles", "speaker", "terminal", "text_tool", "timer", "volume", "wave", "zap",
}

blocks = re.findall(r'line_icon!\(\s*([A-Z_]+)\s*,\s*"([^"]+)"\s*,\s*\[(.*?)\]\s*\)', source, re.S)
if not blocks:
    sys.exit("no line_icon! blocks found")
for stale in out.glob("hex_icon_*.xml"):
    stale.unlink()
blocks = [b for b in blocks if b[0].lower() in USED]
for constant, _name, body in blocks:
    paths = re.findall(r'"([^"]*)"', body)
    xml = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by tools/icons-from-hex.py from Hex's {constant} line icon. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp"',
        '    android:viewportWidth="24" android:viewportHeight="24">',
    ]
    for d in paths:
        xml.append(
            f'    <path android:pathData="{d}" android:fillColor="#00000000"'
            ' android:strokeColor="#FFFFFFFF" android:strokeWidth="1.75"'
            ' android:strokeLineCap="round" android:strokeLineJoin="round" />'
        )
    xml.append("</vector>")
    (out / f"hex_icon_{constant.lower()}.xml").write_text("\n".join(xml) + "\n")
print(f"{len(blocks)} icons")
